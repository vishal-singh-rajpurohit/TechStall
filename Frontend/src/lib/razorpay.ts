/**
 * Launches Razorpay Checkout.
 * - If Razorpay Key is a placeholder/test mock (or script cannot connect), opens the built-in Sandbox Simulator.
 * - If a genuine Razorpay Key is provided, launches the real Razorpay payment modal with fallback safety.
 */
export async function launchRazorpayPayment(opts: RazorpayCheckoutOptions): Promise<void> {
  const key = getRazorpayKey();

  // If key is a placeholder or mock test ID, directly use the interactive Sandbox Simulator
  if (isPlaceholderRazorpayKey(key)) {
    openRazorpaySandboxModal(opts);
    return;
  }

  // If genuine key is configured, load Razorpay script
  const isLoaded = await loadRazorpayScript();

  if (!isLoaded || !window.Razorpay) {
    console.warn('[Razorpay] Gateway script unavailable. Falling back to Sandbox Simulator.');
    openRazorpaySandboxModal(opts);
    return;
  }

  const amountInPaise = Math.round(opts.amount * 100);

  try {
    // Only pass order_id if it's a real Razorpay server order.
    // If it's an internal fallback UUID like order_xxxxxxxxxxxxxx without server registration,
    // omitting order_id allows Razorpay to accept client-side direct capture without throwing 'BAD_REQUEST_ERROR: The id provided does not exist'.
    const isServerRazorpayOrder = opts.razorpayOrderId && !opts.razorpayOrderId.startsWith('order_sim_');

    const options: RazorpayOptions = {
      key,
      amount: amountInPaise,
      currency: (opts.currency || 'INR').toUpperCase(),
      name: 'TechStall Computer Hardware',
      description: `Payment for Order #${opts.orderId.slice(0, 8).toUpperCase()}`,
      image: 'https://images.unsplash.com/photo-1527443224154-c4a3942d3acf?w=120&auto=format&fit=crop&q=80',
      ...(isServerRazorpayOrder ? { order_id: opts.razorpayOrderId } : {}),
      prefill: {
        name: opts.customer.name || 'Valued Customer',
        email: opts.customer.email || 'customer@example.com',
        contact: opts.customer.contact || '',
      },
      notes: {
        order_id: opts.orderId,
        delivery_address: opts.address || '',
        platform: 'TechStall Storefront',
      },
      theme: {
        color: '#ea580c', // brand-600
        backdrop_color: 'rgba(15, 23, 42, 0.65)',
      },
      modal: {
        backdropclose: false,
        escape: true,
        handleback: true,
        confirm_close: true,
        ondismiss: () => {
          if (opts.onDismiss) opts.onDismiss();
        },
      },
      handler: async (response: RazorpayPaymentSuccessResponse) => {
        try {
          await opts.onSuccess(response);
        } catch (err) {
          if (opts.onError) opts.onError(err);
        }
      },
    };

    const rzp = new window.Razorpay(options);

    rzp.on('payment.failed', (response: RazorpayPaymentFailedResponse) => {
      console.error('Razorpay Payment Failed:', response.error);

      // If Razorpay failed due to non-existent order or invalid key, offer fallback to Sandbox
      const desc = response.error?.description || '';
      if (
        desc.toLowerCase().includes('does not exist') ||
        desc.toLowerCase().includes('invalid key') ||
        desc.toLowerCase().includes('merchant')
      ) {
        console.warn('[Razorpay] Order ID or Key not registered on Razorpay servers. Opening Sandbox mode.');
        openRazorpaySandboxModal(opts);
        return;
      }

      if (opts.onError) {
        opts.onError(new Error(response.error?.description || 'Payment was declined or failed.'));
      }
    });

    rzp.open();
  } catch (err: any) {
    console.warn('[Razorpay] Error initializing modal, switching to Sandbox Simulator:', err);
    openRazorpaySandboxModal(opts);
  }
}
