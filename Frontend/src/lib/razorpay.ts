const RAZORPAY_SCRIPT_URL = 'https://checkout.razorpay.com/v1/checkout.js';

/**
 * Dynamically loads the official Razorpay Checkout SDK script if not already present.
 */
export function loadRazorpayScript(): Promise<boolean> {
  return new Promise((resolve) => {
    if (typeof window === 'undefined') {
      return resolve(false);
    }

    if (window.Razorpay) {
      return resolve(true);
    }

    // Check if script tag already exists
    const existingScript = document.querySelector(`script[src="${RAZORPAY_SCRIPT_URL}"]`);
    if (existingScript) {
      existingScript.addEventListener('load', () => resolve(true));
      existingScript.addEventListener('error', () => resolve(false));
      return;
    }

    const script = document.createElement('script');
    script.src = RAZORPAY_SCRIPT_URL;
    script.async = true;
    script.crossOrigin = 'anonymous';

    script.onload = () => {
      resolve(true);
    };

    script.onerror = () => {
      console.warn('Failed to load Razorpay Checkout script from CDN.');
      resolve(false);
    };

    document.body.appendChild(script);
  });
}

/**
 * Returns the public Razorpay Key ID from environment or standard test fallback.
 */
export function getRazorpayKey(): string {
  return (
    process.env.NEXT_PUBLIC_RAZORPAY_KEY_ID!
  );
}

/**
 * Checks whether the current Razorpay key is a mock, placeholder, or invalid test string.
 */
export function isPlaceholderRazorpayKey(key?: string | null): boolean {
  if (!key) return true;
  const normalized = key.trim().toLowerCase();
  if (
    normalized === 'rzp_test_51abcdefghijkl' ||
    normalized.includes('placeholder') ||
    normalized.includes('dummy') ||
    normalized.includes('your_key') ||
    normalized.includes('example') ||
    normalized === 'rzp_test_51abcdefghijk'
  ) {
    return true;
  }
  // Real Razorpay keys start with rzp_test_ or rzp_live_ followed by at least 12 alphanumeric characters
  const pattern = /^rzp_(test|live)_[a-zA-Z0-9]{12,}$/;
  return !pattern.test(key.trim());
}

export interface RazorpayCheckoutOptions {
  orderId: string; // Internal Order UUID
  razorpayOrderId?: string; // Order ID generated by Razorpay backend
  amount: number; // Order amount in Rupees (e.g. 34990)
  currency?: string; // Default: 'INR'
  customer: {
    name?: string | null;
    email?: string | null;
    contact?: string | null;
  };
  address?: string;
  onSuccess: (response: RazorpayPaymentSuccessResponse) => void | Promise<void>;
  onDismiss?: () => void;
  onError?: (error: any) => void;
}

